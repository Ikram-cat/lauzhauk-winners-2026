internal enum class Language(val tag: String) {
    French("fr"),
    English("en"),
    German("de"),
    Italian("it");

    fun text(copy: Copy): String = when (this) {
        French -> copy.french
        English -> copy.english
        German -> copy.german
        Italian -> copy.italian
    }

    fun count(count: Int, singular: Copy, plural: Copy): String =
        "$count ${text(if (count == 1) singular else plural)}"
}

