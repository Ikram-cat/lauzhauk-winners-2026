"""Key pitch numbers, generated from metrics.json and the timelines (no number is typed by hand).

    python -m sbb_duration.pitch [--output-dir DIR]

Writes output/pitch_numbers.md. Run after train, export and sources.
"""
import argparse
import json
from pathlib import Path

import pandas as pd

from .data import OUTPUT_DIR
from .sources import DEMO_BACKUP, DEMO_PRIMARY


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _min(x: float) -> str:
    return f"{x:.1f} min"


def _hm(iso: str | None) -> str:
    return "–" if iso is None else pd.Timestamp(iso).strftime("%H:%M")


def _title(t: dict) -> str:
    """Stations part of the last public summary ("Service resumed: A - B" -> "A - B")."""
    summary = t["incident"]["summaryEn"] or t["incident"]["id"]
    return summary.split(": ", 1)[-1]


def incident_numbers(t: dict) -> dict:
    moments = t["moments"]
    first_public = next(m for m in moments if m["public"] and m["public"]["officialRemainingMinutes"] is not None
                        and m["outlook"]["remainingMinutes"])
    codes = [m["outlook"]["advice"]["code"] for m in moments if m["outlook"]["advice"]["code"] != "UNKNOWN"]
    raw_changes = sum(1 for a, b in zip(codes, codes[1:]) if a != b)
    notified_changes = sum(1 for m in moments for r in m["notify"]["reasons"] if r["code"] == "ADVICE_CHANGED")
    bus_internal = next((m["internal"]["replacementBus"] for m in reversed(moments) if m["internal"]["replacementBus"]), None)
    bus_via = next((m["via"]["replacementBusPublishedAt"] for m in moments if m["via"]["replacementBusPublishedAt"]), None)
    inc = t["incident"]
    lead = None
    if inc["actualResumptionAt"] and inc["publicEndAt"]:
        lead = (pd.Timestamp(inc["publicEndAt"]) - pd.Timestamp(inc["actualResumptionAt"])).total_seconds() / 60
    return {"first": first_public, "raw_changes": raw_changes, "notified_changes": notified_changes,
            "bus_internal": bus_internal, "bus_via": bus_via, "lead": lead}


def render(metrics: dict, primary: dict, backup: dict, index: dict) -> str:
    e = metrics["evaluation"]
    test, split, cal, rob = e["test"], e["split"], e["calibration"], e["robustness"]
    w, a = test["maeMinutes"]["withAnnouncement"], test["maeMinutes"]["all"]
    rr = rob["excludedThenResplit"]["testMetrics"]["maeMinutes"]["withAnnouncement"]
    p, pn = primary, incident_numbers(primary)
    b = backup
    f = pn["first"]
    lines = [
        "# Pitch numbers (generated)",
        "",
        f"Generated by `python -m sbb_duration.pitch` from `metrics.json` (trained {metrics['generatedAt']}) and "
        "`timelines/`. Each line gives the number, then its definition in one sentence. "
        "Demo incidents are historical replays (MOCK), not live data.",
        "",
        "## Model vs the official SBB announcement",
        "",
        f"- **{_min(w['modelP50'])} vs {_min(w['officialSbb'])}** mean error of our median prediction vs the SBB "
        f"announcement ({_pct(1 - w['modelP50'] / w['officialSbb'])} smaller). Mean absolute difference between the "
        f"predicted (or announced) remaining time and the real remaining time, over the {w['snapshots']} moments "
        f"with an announcement of the {split['test']['incidents']} most recent incidents (after "
        f"{split['cutoff'][:10]}), never seen in training.",
        f"- **{_min(a['modelP50'])} vs {_min(a['medianPerCause'])}** mean error of our model vs a simple rule "
        f"(median remaining time per cause). Same test moments ({a['snapshots']}), including those without an "
        "announcement.",
        f"- **{_pct(test['officialTooOptimisticShare'])}** of SBB announcements are too optimistic. Share of test "
        "moments where the announced end comes before the real end.",
        f"- **{_min(rr['modelP50'])} vs {_min(rr['officialSbb'])}** robustness: the same comparison after removing the "
        f"{rob['autoClosedIncidents']} incidents that close 0–2 min after their last announced end (an automatic "
        "close at the announced time) and redoing the chronological split.",
        "",
        "## Pessimistic estimate",
        "",
        f"- **{_pct(cal['testCoverageAfter'])}** of real ends fall before our pessimistic estimate (target "
        f"{_pct(cal['target'])}; {_pct(cal['testCoverageBefore'])} before calibration). Share of test moments where "
        "the real remaining time is at most the pessimistic estimate; the calibration is a split-conformal offset "
        f"fitted on the {cal['calibrationIncidents']} most recent training incidents.",
        "",
        f"## Demo incident: {_title(p)} ({p['incident']['startedAt'][:10]})",
        "",
        f"- **{f['public']['officialRemainingMinutes']} min announced vs {f['actualRemainingMinutes']} min real** at "
        f"{_hm(f['at'])}: the first SBB announcement vs the real remaining time; we predicted "
        f"{f['outlook']['remainingMinutes']['p50']} min (pessimistic {f['outlook']['remainingMinutes']['pessimistic']}).",
        f"- **{_min(p['comparison']['meanAbsErrorMinutes']['modelP50'])} vs "
        f"{_min(p['comparison']['meanAbsErrorMinutes']['officialSbb'])}** mean error of our prediction vs the SBB "
        f"announcement over the incident ({p['comparison']['moments']} moments), measured against the real "
        "resumption.",
    ]
    if pn["lead"] is not None:
        lines.append(
            f"- **{pn['lead'] / 60:.1f} h earlier**: trains ran again at {_hm(p['incident']['actualResumptionAt'])} "
            f"according to the internal liveticker, while the public feed closed at {_hm(p['incident']['publicEndAt'])}. "
            "Time between the internal resumption message and the public end.")
    if pn["bus_internal"]:
        lines.append(
            f"- **{pn['bus_internal']['busCount']} replacement buses** known internally at "
            f"{_hm(pn['bus_internal']['firstAt'])}, published by VIA at {_hm(pn['bus_via'])}. First internal message "
            "mentioning replacement buses vs first VIA publication of the replacement service.")
    lines += [
        f"- **{p['notifications']} notifications** for {len(p['moments'])} updates, and **{pn['notified_changes']} "
        f"of {pn['raw_changes']}** raw advice changes notified. Notification rules: first detection, confirmed advice "
        "change, announced end shifted > 15 min, replacement bus; at most one every 15 min.",
        "",
        f"## Backup incident: {_title(b)} ({b['incident']['startedAt'][:10]})",
        "",
        f"- **{_min(b['comparison']['meanAbsErrorMinutes']['modelP50'])} vs "
        f"{_min(b['comparison']['meanAbsErrorMinutes']['officialSbb'])}** mean error of our prediction vs the SBB "
        f"announcement ({b['comparison']['moments']} moments), against the public end, which matches the end of "
        "operations.",
        "",
        "## Data",
        "",
        f"- **{metrics['data']['snapshotIncidents']} incidents, {metrics['data']['snapshots']} moments** used for "
        f"training and testing, {metrics['data']['firstIncidentStart'][:10]} to {metrics['data']['lastIncidentStart'][:10]}. "
        "Incidents with a known end from the SBB public liveticker; a moment is one published version while it "
        "was ongoing.",
        f"- **{index['linkage']['inAllThreeSources']} incidents in all three sources** (public liveticker, VIA, internal "
        f"liveticker; {index['linkage']['internalLinkedToVia']} of {index['linkage']['internalCases']} internal cases "
        "linked to VIA). Incidents of September 2026 joined by id (VIA ↔ public) and by cause plus creation time "
        "within 30 min (internal ↔ VIA).",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
    args = parser.parse_args(argv)
    out = args.output_dir
    load = lambda path: json.loads((out / path).read_text(encoding="utf-8"))
    text = render(load("metrics.json"), load(f"timelines/timeline-{DEMO_PRIMARY}.json"),
                  load(f"timelines/timeline-{DEMO_BACKUP}.json"), load("timelines/index.json"))
    (out / "pitch_numbers.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
